  const LANG_ORDER = ['zh-CN', 'en', 'ja', 'ko', 'es', 'de', 'fr'];

  function readSavedLang() {
    try { return localStorage.getItem('collage-lang'); } catch (err) { return null; }
  }

  function detectFromBrowser() {
    const langs = navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || ''];
    for (const raw of langs) {
      const lower = String(raw).toLowerCase();
      const exact = LANG_ORDER.find((code) => code.toLowerCase() === lower);
      if (exact) return exact;
      const base = lower.split('-')[0];
      const hit = LANG_ORDER.find((code) => code.toLowerCase().split('-')[0] === base);
      if (hit) return hit;
    }
    return 'en';
  }

  function detect() {
    const saved = readSavedLang();
    if (saved && I18N[saved]) return saved;
    return detectFromBrowser();
  }

  const api = {
    dict: I18N,
    order: LANG_ORDER,
    detect,
    detectFromBrowser,
    readSavedLang,
    save(code) {
      if (!I18N[code]) return;
      try { localStorage.setItem('collage-lang', code); } catch (err) { /* noop */ }
    },
    clear() {
      try { localStorage.removeItem('collage-lang'); } catch (err) { /* noop */ }
    }
  };

  window.__collageI18n = api;

  // 在首屏解析阶段就把 <html lang> 设为检测到的语言，避免语言闪烁
  const initial = detect();
  document.documentElement.lang = I18N[initial].htmlLang;
  document.documentElement.dataset.lang = initial;
